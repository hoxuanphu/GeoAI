"""Internal lifetime contract supplied by the native execution owner."""
from typing import Protocol


class GuardLease(Protocol):
    def assert_held(self, project_id: str) -> None: ...
    def close(self) -> None: ...


class WriterGuard(Protocol):
    @property
    def owner_id(self) -> str: ...
    @property
    def owner_epoch(self) -> int: ...
    def assert_held(self, project_id: str) -> None: ...
    def retain(self, project_id: str) -> GuardLease: ...
    def close(self) -> None: ...


class OwnerStopEvidence(Protocol):
    """Trusted native observer proves every group of an old generation stopped."""
    def assert_stopped(self, project_id: str, owner_id: str, owner_epoch: int) -> None: ...
